// camelCase: The first word is lowercase, and the first letter of each subsequent word is capitalized (e.g., myVariableName, calculateTotalPrice). This is the standard convention for variable and function names in JavaScript.

// PascalCase: The first letter of every word is capitalized (e.g., MyVariableName, CalculateTotalPrice). This is often used for class names or constructor functions in JavaScript.

